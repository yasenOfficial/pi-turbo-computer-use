#!/usr/bin/env node
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { existsSync, readdirSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
const releases = path.join(os.homedir(), ".local/share/pi-codex-ultra/releases");
const sdk = [process.env.PI_CODING_AGENT_PACKAGE, ...readdirSync(releases).sort().reverse().map(r => path.join(releases, r, "node_modules/@earendil-works/pi-coding-agent/package.json"))].find(p => p && existsSync(p));
const require = createRequire(sdk);
const { createJiti } = await import(pathToFileURL(require.resolve("jiti")));
const jiti = createJiti(import.meta.url, { moduleCache: false, alias: { typebox: require.resolve("typebox") } });
const { ComputerUseRouting } = await jiti.import(path.resolve(import.meta.dirname, "../.pi/extensions/computer-use/routing.ts"));
const model = (provider, id) => ({ provider, id, api: "fixture" });
const a = "codex-qsen5", b = "codex-other";
const original = model(a, "gpt-5.0"), sol6 = model(a, "gpt-5.6-sol"), sol10 = model(a, "gpt-5.10-sol");
const luna6 = model(a, "gpt-5.6-luna"), luna10 = model(a, "gpt-5.10-luna"), luna12 = model(a, "gpt-5.12-luna");
const other = model(b, "gpt-5.0"), otherSol = model(b, "gpt-5.10-sol"), otherLuna = model(b, "gpt-5.12-luna");
let available = [original, sol6, sol10, luna6, luna10, luna12, other, otherSol, otherLuna];
let current = original, enabled = true, waiting = false, fail = false, pending;
const entries = [], labels = [], handlers = new Map(), tools = new Map(), selections = [];
const ctx = { get model() { return current; }, hasUI: false, signal: undefined,
	modelRegistry: { getAvailable: () => available }, sessionManager: { getBranch: () => entries } };
const pi = { registerTool: d => tools.set(d.name, d), appendEntry: (customType, data) => entries.push({ type: "custom", customType, data }),
	on: (name, fn) => { handlers.set(name, [...handlers.get(name) ?? [], fn]); },
	setModel: async m => { selections.push(m); if (pending) await pending; if (fail) return false;
		const previousModel = current; current = m; await emit("model_select", { previousModel, model: m }); return true; } };
const mode = { isEnabled: () => enabled, isWaitingForUser: () => waiting, setRoutingLabel: (label) => labels.push(label) };
const routing = new ComputerUseRouting(pi, mode);
const emit = async (name, event = {}, context = ctx) => { for (const fn of handlers.get(name) ?? []) await fn(event, context); };
const before = async () => { const event = { prompt: "task", systemPromptOptions: { sections: {} } }; await routing.beforeStart(event, ctx); return event; };
const tool = tools.get("desktop_model_phase");
const call = (input, signal) => tool.execute("id", input, signal, undefined, ctx);
const block = (toolName, toolCallId, input) => routing.guard({ toolName, toolCallId, input }, ctx)?.block;
assert.equal(pi.registerVirtualModel, undefined, "no virtual model is registered or visible in /model");
assert.equal(tool.exposure, "model-only");
await routing.start(ctx);
assert.match(routing.summary(ctx), /single/);
for (const obsolete of ["status", "list", "sol codex-qsen5/gpt-5.6-sol", "luna codex-qsen5/gpt-5.6-luna"])
	await assert.rejects(() => routing.command(obsolete, ctx), /Usage: models hybrid\|single/);
const previousEntries = entries.length;
enabled = false;
await routing.command("hybrid", ctx);
assert.equal(current, original, "command changes preference only; no model switch");
assert.equal(selections.length, 0);
assert.match(routing.summary(ctx), /Sol gpt-5.10-sol; Luna gpt-5.10-luna/);
assert.equal(labels.at(-1), undefined, "hybrid preference does not show an OFF bar");
assert.ok(entries.length > previousEntries);
assert.equal((await before()).systemPromptOptions.sections.computer_use_routing, undefined);
assert.equal(current, original, "OFF ordinary question stays on current physical model");
assert.equal(labels.at(-1), undefined, "OFF hides routing label");
assert.equal(block("desktop_observe"), true);
assert.equal(block("desktop_launch_app", undefined, { query: "CubeIDE" }), true, "OFF also blocks metadata lookup");
assert.match(routing.guard({ toolName: "desktop_request_user", input: { reason: "technical" } }, ctx)?.reason ?? "", /OFF/);
await assert.rejects(() => call({ phase: "execute", plan: "plan" }), /OFF/);
enabled = true;
routing.refreshLabel(ctx); // Parent calls this immediately after /computer-use on.
assert.match(labels.at(-1), /gpt-5.10-sol → gpt-5.10-luna$/,
	"ON renders selected models before the first task, with no footer change or model call");
assert.equal(selections.length, 0);
await before();
assert.equal(current, sol10, "Sol selected before native first request");
assert.match(labels.at(-1), /план: Sol/);
assert.equal(block("desktop_click"), true);
assert.equal(block("desktop_batch"), true);
assert.equal(block("desktop_launch_app", undefined, { query: "STM32CubeIDE" }), undefined, "Sol can discover installed apps without dispatch");
assert.equal(block("desktop_request_user", undefined, { reason: "technical" }), undefined,
	"Sol planning may report an unrecoverable backend blocker");
for (const invalid of [{ app_id: "xed.desktop" }, { name: "Editor" }, { query: "CubeIDE", app_id: "xed.desktop" },
	{ query: "CubeIDE", name: "Editor" }, { query: "CubeIDE", exec: "evil" }, { query: "" }, { query: "   " },
	{ query: "bad\nquery" }, { query: "é".repeat(121) }, {}])
	assert.equal(block("desktop_launch_app", undefined, invalid), true, `Sol cannot dispatch/malformed query: ${JSON.stringify(invalid)}`);
assert.equal(block("desktop_focus_window"), undefined);
assert.equal(block("desktop_observe"), undefined);
assert.equal(block("desktop_screenshot"), undefined, "visual policy alone controls capture");
await emit("message_end", { message: { role: "assistant", content: [
	{ type: "toolCall", id: "mixed-a", name: "desktop_model_phase" }, { type: "toolCall", id: "mixed-b", name: "desktop_click" }] } });
assert.equal(block("desktop_model_phase", "mixed-a"), true);
assert.equal(block("desktop_click", "mixed-b"), true);
await assert.rejects(() => call({ phase: "escalate", reason: "error", verified_state: "observed" }), /Wrong physical model/);
await assert.rejects(() => call({ phase: "execute", plan: "" }), /bounded plan/);
let release;
pending = new Promise(resolve => { release = resolve; });
const switching = call({ phase: "execute", plan: "Inspect then act" });
assert.equal(block("desktop_click"), true, "no companion input during model switch");
release();
const handedOff = await switching; pending = undefined;
assert.match(handedOff.content[0].text, /query.*lookup does not launch.*verified returned app_id/);
assert.match(handedOff.content[0].text, /Before technical user handoff.*escalate/);
assert.equal(current, luna10);
assert.match(labels.at(-1), /изпълнява: Luna/);
const switchCount = selections.length;
await emit("tool_execution_end", { toolName: "desktop_click", isError: true });
await emit("session_compact", {});
assert.equal(current, luna10, "tool errors and compaction do not escalate or change physical model");
assert.equal(selections.length, switchCount);
assert.equal(block("desktop_click"), undefined);
assert.equal(block("desktop_launch_app", undefined, { app_id: "xed.desktop" }), undefined, "Luna may launch after handoff");
assert.match(routing.guard({ toolName: "desktop_request_user", input: { reason: "technical", instructions: "Please fix it" } }, ctx)?.reason ?? "",
	/Technical user handoff requires Sol review.*re-observe.*bounded materially different.*escalate.*No automatic escalation\/replay/);
for (const reason of ["login", "mfa", "captcha", "approval", "clarification"])
	assert.equal(block("desktop_request_user", undefined, { reason }), undefined, `${reason} handoff stays immediate`);
assert.equal(block("desktop_model_phase"), undefined);
const interrupted = new AbortController(); interrupted.abort();
assert.match(routing.guard({ toolName: "desktop_request_user", input: { reason: "technical" } },
	{ ...ctx, signal: interrupted.signal })?.reason ?? "", /cancelled/);
waiting = true;
assert.equal(block("desktop_click"), true);
assert.match(routing.guard({ toolName: "desktop_request_user", input: { reason: "technical" } }, ctx)?.reason ?? "", /waiting for user/);
await assert.rejects(() => call({ phase: "escalate", reason: "blocked", verified_state: "observed" }), /Action required/);
waiting = false;
await assert.rejects(() => call({ phase: "escalate", reason: "error" }), /verified state/);
assert.equal(current, luna10, "tool failure alone cannot escalate");
await call({ phase: "escalate", reason: "verified blocker", verified_state: "observed current form" });
assert.equal(current, sol10);
assert.match(labels.at(-1), /блокаж: Sol/);
assert.equal(block("desktop_request_user", undefined, { reason: "technical" }), undefined, "Sol may make an exhausted technical handoff after review");
await assert.rejects(() => call({ phase: "escalate", reason: "again", verified_state: "observed" }), /Wrong physical model/);
const abort = new AbortController(); abort.abort();
await assert.rejects(() => call({ phase: "execute", plan: "plan" }, abort.signal), /cancelled/);
await emit("agent_settled");
assert.equal(current, original, "settlement restores original only while owned");
assert.match(labels.at(-1), /gpt-5.10-sol → gpt-5.10-luna$/);
await before();
assert.equal(current, sol10, "new user task resets escalation");
await call({ phase: "execute", plan: "Only execute" });
await emit("agent_settled");
assert.equal(current, original, "normal Sol → Luna completion restores original");
await before();
await call({ phase: "execute", plan: "Verify then stop" });
assert.equal(current, luna10);
assert.equal(block("desktop_stop"), undefined);
assert.equal(block("desktop_observe"), true, "Stop disables all further desktop actions");
const stoppedAbort = new AbortController(); stoppedAbort.abort();
await emit("agent_settled", {}, { ...ctx, signal: stoppedAbort.signal });
assert.equal(current, original, "Stop and aborted run signal still restore owned physical model metadata");
assert.equal(block("desktop_click"), true, "Stop gate remains sticky after settlement");
assert.equal(block("desktop_launch_app", undefined, { query: "CubeIDE" }), true, "Stop disables lookup for this task");
assert.match(routing.guard({ toolName: "desktop_request_user", input: { reason: "technical" } }, ctx)?.reason ?? "", /disabled/, "Stop remains dominant over technical handoff review");
await before();
await call({ phase: "execute", plan: "Observe" });
current = other;
await emit("model_select", { previousModel: luna10, model: other });
await emit("agent_settled");
assert.equal(current, other, "manual override during Luna is never replaced on settlement");
current = other;
await emit("model_select", { previousModel: original, model: other });
await before();
assert.equal(current, otherSol, "new task uses current physical account, not saved earlier provider");
assert.match(routing.summary(ctx), /account codex-other; Sol gpt-5.10-sol; Luna gpt-5.12-luna/);
current = other;
await emit("model_select", { previousModel: otherSol, model: other });
assert.equal(block("desktop_observe"), true);
current = otherSol;
assert.equal(block("desktop_model_phase"), true, "switch away and back cannot resume queued calls");
assert.equal(block("desktop_stop"), undefined);
assert.equal(block("desktop_ping"), undefined);
assert.equal(block("desktop_metrics"), undefined);
await emit("agent_settled");
assert.equal(block("desktop_click"), true, "settlement does not clear disabled gate");
await before();
assert.equal(block("desktop_observe"), undefined, "new prompt clears disabled state");
assert.equal(block("desktop_stop"), undefined);
assert.equal(block("desktop_click"), true, "Stop disables the active task");
await routing.start(ctx);
assert.equal(block("desktop_batch"), true, "branch restore keeps disabled state");
current = other;
await emit("model_select", { previousModel: otherSol, model: other });
await before();
assert.equal(current, otherSol);
fail = true;
await assert.rejects(() => call({ phase: "execute", plan: "Do it" }), /Unable to select/);
assert.equal(current, otherSol, "failed switch does not commit a phase or repeat input");
fail = false;
await emit("agent_settled");
assert.equal(current, other, "failed handoff still restores original at settlement");
available = [original, sol6, luna6, other, otherLuna];
await assert.rejects(() => routing.command("hybrid", ctx), /No authenticated Sol on current account codex-other/);
available = [original, sol6, luna6, other, otherSol];
await assert.rejects(() => routing.command("hybrid", ctx), /No authenticated Luna on current account codex-other/);
assert.equal(current, other, "missing current-account targets never switch providers");
available = [original, sol6, sol10, luna6, luna10, luna12, other, otherSol, otherLuna];
await routing.command("hybrid", ctx);
// Authentication/availability can change after an idle command: before_agent_start
// errors are not fatal in Pi, so the task must inject an explanation and block tools.
available = [original, sol6, luna6, other, otherSol];
const warnings = [];
ctx.hasUI = true;
ctx.ui = { notify: (text, level) => warnings.push({ text, level }) };
const failedStart = await before();
assert.match(failedStart.systemPromptOptions.sections.computer_use_routing, /Hybrid model selection failed: No authenticated Luna.*No desktop action permitted/);
assert.match(failedStart.systemPromptOptions.sections.computer_use_routing, /do not call desktop tools or silently fall back/);
assert.equal(warnings.at(-1).level, "warning");
assert.equal(current, other, "missing Luna must not switch the account or model");
assert.equal(block("desktop_observe"), true);
assert.equal(block("desktop_model_phase"), true);
assert.equal(block("desktop_stop"), undefined);
assert.equal(block("desktop_ping"), undefined);
await emit("agent_settled");
available = [original, sol6, sol10, luna6, luna10, luna12, other, otherSol, otherLuna];
enabled = false;
await routing.command("single", ctx);
assert.equal(current, other, "single does not switch the manually selected model");
assert.equal(labels.at(-1), undefined, "OFF keeps single-model bar hidden");
enabled = true;
routing.refreshLabel(ctx);
assert.equal(labels.at(-1), `single · ${other.id}`, "ON single mode shows the current physical model in the same bar");
const legacy = model("computer-use", "sol-luna");
current = legacy;
await routing.start(ctx);
assert.equal(current, other, "old virtual branch selection migrates to saved physical model");
console.log("Physical routing fake: OFF, account selection, native handoffs, stop, guards, abort, settlement and legacy migration passed");
