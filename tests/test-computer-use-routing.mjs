#!/usr/bin/env node
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { existsSync, readdirSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
const releases = path.join(os.homedir(), ".local/share/pi-codex-ultra/releases");
const sdk = [process.env.PI_CODING_AGENT_PACKAGE,
	process.env.PI_CODEX_ULTRA_RELEASE_ROOT && path.join(process.env.PI_CODEX_ULTRA_RELEASE_ROOT, "node_modules/@earendil-works/pi-coding-agent/package.json"),
	...(existsSync(releases) ? readdirSync(releases).sort().reverse().map(r => path.join(releases, r, "node_modules/@earendil-works/pi-coding-agent/package.json")) : [])].find(p => p && existsSync(p));
if (!sdk) throw new Error("Compatible Pi SDK not found; set PI_CODING_AGENT_PACKAGE");
const require = createRequire(sdk);
const { createJiti } = await import(pathToFileURL(require.resolve("jiti")));
const jiti = createJiti(import.meta.url, { moduleCache: false, alias: { typebox: require.resolve("typebox"), "@earendil-works/pi-tui": require.resolve("@earendil-works/pi-tui") } });
const { ComputerUseRouting } = await jiti.import(path.resolve(import.meta.dirname, "../.pi/extensions/computer-use/routing.ts"));
const { computerUseMessage } = await jiti.import(path.resolve(import.meta.dirname, "../.pi/extensions/computer-use/instructions.ts"));
const sol = { provider: "fixture", id: "gpt-sol", api: "fixture" };
const luna = { provider: "fixture", id: "gpt-luna", api: "fixture" };
const original = { provider: "fixture", id: "gpt-original", api: "fixture" };
const vm = { provider: "computer-use", id: "sol-luna", api: "pi-virtual" };
let available = [sol, luna, original];
let current = sol;
let waiting = false;
let enabled = true;
const entries = [], statuses = [], handlers = new Map(), tools = new Map();
let virtualDefinition;
const pi = { registerVirtualModel: d => { virtualDefinition = d; }, registerTool: d => tools.set(d.name, d),
	appendEntry: (customType, data) => entries.push({ type: "custom", customType, data }),
	setModel: async m => { current = m; return true; },
	on: (name, fn) => { handlers.set(name, [...handlers.get(name) ?? [], fn]); } };
const ctx = { get model() { return current; }, hasUI: true, ui: { setStatus: (...args) => statuses.push(args) },
	modelRegistry: { getAvailable: () => available, find: (p, id) => [...available, vm].find(m => m.provider === p && m.id === id) },
	sessionManager: { getBranch: () => entries } };
const mode = { isEnabled: () => enabled, isWaitingForUser: () => waiting };
const routing = new ComputerUseRouting(pi, mode);
const emit = async (name, event = {}) => { for (const fn of handlers.get(name) ?? []) await fn(event, ctx); };
const before = (prompt = "desktop task") => {
	const event = { prompt, systemPromptOptions: { sections: {} } };
	routing.beforeStart(event, ctx);
	return event;
};
const request = (reason, state, previous, failed) => virtualDefinition.route({ reason, state, previous, failed, thinkingLevel: "medium", messages: [] }, ctx);
const phase = tools.get("desktop_model_phase");
const call = async input => phase.execute("tool", input, undefined, undefined, ctx);
const blocked = name => routing.guard({ toolName: name }, ctx)?.block;
assert.equal(phase.exposure, "model-only");
assert.equal(virtualDefinition.provider, "computer-use");
assert.equal(virtualDefinition.id, "sol-luna");
await assert.rejects(() => call({ phase: "execute", plan: "test" }), /No active/);
routing.start(ctx);
assert.match(await routing.command("status", ctx), /single/);
const countBeforeList = entries.length;
const selectedBeforeList = current;
assert.match(await routing.command("list", ctx), /fixture\/gpt-luna/);
assert.equal(entries.length, countBeforeList, "listing must not persist changes");
assert.equal(current, selectedBeforeList, "listing must not select a model");
await routing.command("models".replace("models", "hybrid"), ctx);
assert.equal(current, vm);
enabled = false;
assert.equal(before(computerUseMessage("one-off desktop task")).systemPromptOptions.sections.computer_use_routing, undefined,
	"wrapped tasks cannot activate hybrid while mode is OFF");
assert.equal(request("user").model, sol, "OFF routes to saved original physical model despite virtual selection");
await assert.rejects(() => call({ phase: "execute", plan: "Do it" }), /OFF/);
enabled = true;
before();
const planRoute = request("user");
assert.equal(planRoute.model, sol);
assert.match(planRoute.state.taskId, /-/);
assert.equal(blocked("desktop_click"), true);
assert.equal(blocked("desktop_batch"), true);
assert.equal(blocked("desktop_set_text"), true);
assert.equal(blocked("desktop_launch_app"), true);
assert.equal(blocked("desktop_focus_window"), undefined);
assert.equal(blocked("desktop_observe"), undefined);
assert.equal(blocked("desktop_screenshot"), undefined, "visual authorization is handled by visual policy, not the mutation guard");
await emit("message_end", { message: { role: "assistant", content: [{ type: "toolCall", id: "x", name: "desktop_model_phase" }, { type: "toolCall", id: "y", name: "desktop_click" }] } });
assert.equal(routing.guard({ toolCallId: "x", toolName: "desktop_model_phase" }, ctx)?.block, true);
assert.equal(routing.guard({ toolCallId: "y", toolName: "desktop_click" }, ctx)?.block, true);
await assert.rejects(() => call({ phase: "escalate", reason: "blocked", verified_state: "observed" }), /Wrong model/);
await assert.rejects(() => call({ phase: "execute", plan: "" }), /requires a bounded plan/);
await call({ phase: "execute", plan: "Inspect, then safely act" });
assert.equal(blocked("desktop_click"), true, "do not mutate in Sol's handoff batch");
const execRoute = request("continuation", planRoute.state, { model: sol });
assert.equal(execRoute.model, luna);
assert.equal(blocked("desktop_click"), undefined);
enabled = false;
assert.throws(() => request("continuation", execRoute.state), /OFF/, "turning OFF midtask cannot continue routing");
await assert.rejects(() => call({ phase: "escalate", reason: "blocked", verified_state: "observed" }), /OFF/);
enabled = true;
const retry = request("retry", execRoute.state, { model: sol }, { model: luna, message: { stopReason: "error" } });
assert.equal(retry.model, luna, "failed Luna request remains on Luna");
await assert.rejects(() => call({ phase: "escalate", reason: "error" }), /requires a reason and current verified state/);
waiting = true;
assert.equal(blocked("desktop_click"), true);
await assert.rejects(() => call({ phase: "escalate", reason: "blocked", verified_state: "observed" }), /Action required/);
waiting = false;
await call({ phase: "escalate", reason: "verified blocker", verified_state: "observed form, no input replay" });
assert.equal(blocked("desktop_click"), true);
const fallback = request("continuation", execRoute.state, { model: luna });
assert.equal(fallback.model, sol);
assert.equal(request("continuation", fallback.state, { model: sol }).model, sol);
await assert.rejects(() => call({ phase: "escalate", reason: "again", verified_state: "observed" }), /Wrong model/);
const ac = new AbortController(); ac.abort();
assert.throws(() => virtualDefinition.route({ reason: "continuation", state: fallback.state, thinkingLevel: "off", signal: ac.signal }, ctx), /cancelled/);
current = luna;
await emit("model_select", { previousModel: vm, model: luna, source: "set" });
assert.match(await routing.command("status", ctx), /idle/, "manual physical selection disables routing phase");
current = vm;
assert.throws(() => request("continuation", fallback.state), /routing disabled/, "switching back does not silently resume unsafe phase");
for (const name of ["desktop_click", "desktop_observe", "desktop_visual_permission", "desktop_model_phase"])
	assert.equal(blocked(name), true, `queued ${name} remains blocked after model switch away/back`);
for (const name of ["desktop_stop", "desktop_ping", "desktop_metrics"])
	assert.equal(blocked(name), undefined, `${name} remains available for emergency/control`);
await emit("agent_settled");
assert.match(await routing.command("status", ctx), /idle/);
assert.equal(blocked("desktop_batch"), true, "settlement cannot reauthorize queued input");
await routing.command("luna fixture/gpt-luna", ctx);
before("new task");
assert.equal(request("user", fallback.state).model, sol, "new user task resets escalation");
assert.equal(blocked("desktop_observe"), undefined, "new user prompt clears disabled state");
routing.start(ctx);
assert.equal(request("continuation").model, sol, "branch restore recovers plan");
assert.equal(request("direct", undefined, { model: luna }).model, luna, "compaction sticks to available physical model");
assert.equal(blocked("desktop_stop"), undefined, "emergency Stop remains available during a task");
assert.equal(blocked("desktop_batch"), true, "Stop disables the task's pending input");
assert.throws(() => request("continuation"), /routing disabled/, "Stop cannot automatically resume routing");
enabled = false;
before("ordinary question");
assert.equal(request("user").model, sol, "ordinary question uses original physical model");
available = [sol, original];
await assert.rejects(() => routing.command("hybrid", ctx), /unavailable or missing authentication/);
available = [sol, luna, original];
await routing.command("single", ctx);
assert.equal(current, sol);
assert.equal(statuses.at(-1)[1], undefined);
const conflict = { provider: "fixture", id: "other-luna", api: "fixture" };
available = [sol, original, conflict, { provider: "fixture", id: "another-luna", api: "fixture" }];
const r2 = new ComputerUseRouting({ ...pi, appendEntry: () => {} }, mode);
assert.ok(r2);
await assert.rejects(() => r2.command("hybrid", ctx), /Luna target ambiguous.*fixture\/other-luna/);
assert.match(await r2.command("list", ctx), /fixture\/another-luna/);
const r3 = new ComputerUseRouting({ ...pi, appendEntry: () => {} }, mode);
current = original;
available = [sol, { provider: "other", id: "second-sol", api: "fixture" }, luna, original];
await assert.rejects(() => r3.command("hybrid", ctx), /Sol target ambiguous/);
current = sol;
available = [sol, luna, original];
const noSelection = new ComputerUseRouting({ ...pi, setModel: async () => false, appendEntry: () => {} }, mode);
await assert.rejects(() => noSelection.command("hybrid", ctx), /Unable to select/);
assert.match(await noSelection.command("status", ctx), /single/, "failed selection does not persist hybrid preference");
const legacy = new ComputerUseRouting({ registerTool() {}, on() {} }, mode);
await assert.rejects(() => legacy.command("hybrid", ctx), /registerVirtualModel/);
console.log("Computer-use routing fake registry: phases, guards, retry, abort, branch, auth and ordinary prompts passed");
